window.PP = window.PP || {};

// Можно ли перевести проект с этапа stage на следующий (или закрыть последний этап исходом).
// stage.tasks: [{ t, done, opt }], opt = задача «по желанию».
// Возвращает { ok: true } или { ok: false, why: 'подсказка для МПП' }.
PP.canMoveNext = function (stage) {
  // TODO(команда): решите правило перехода. Сейчас: выполнены все обязательные задачи,
  // задачи «по желанию» не мешают. Варианты: разрешить переход с комментарием
  // «почему пропустили», или требовать хотя бы одну задачу «по желанию».
  const left = stage.tasks.filter(x => !x.done && !x.opt);
  if (left.length) return { ok: false, why: 'Осталось задач: ' + left.length };
  return { ok: true };
};
